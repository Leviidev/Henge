static inline void hv_ds4_u16(uint8_t *p, int v) { p[0]=(uint8_t)v;p[1]=(uint8_t)((unsigned)v>>8); }
static inline uint8_t hv_ds4_axis(const uint8_t *p) {
    int value=(int16_t)(p[0]|(unsigned)p[1]<<8);
    if(value < -32767)value=-32767;
    return (uint8_t)((((int64_t)value+32767)*255+32767)/65534);
}
static inline void hv_ds4_pack(uint8_t out[HV_DS4_BYTES],const uint8_t state[HV_GAMEPAD_BYTES],uint64_t sequence) {
    memset(out,0,HV_DS4_BYTES);out[0]=1;
    for(unsigned i=0;i<4;i++)out[1+i]=hv_ds4_axis(state+3+2*i);
    unsigned buttons=state[0]|(unsigned)state[1]<<8;
    out[5]=(state[2]<8?state[2]:8)|((buttons&1)?0x20:0)|((buttons&2)?0x40:0)|((buttons&4)?0x10:0)|((buttons&8)?0x80:0);
    out[6]=((buttons&16)?1:0)|((buttons&32)?2:0)|(state[11]?4:0)|(state[12]?8:0)|
           ((buttons&512)?16:0)|((buttons&256)?32:0)|((buttons&64)?64:0)|((buttons&128)?128:0);
    out[7]=(uint8_t)((sequence&63)<<2)|((buttons&1024)?1:0)|((buttons&2048)?2:0);
    out[8]=state[11];out[9]=state[12];hv_ds4_u16(out+10,(int)(sequence*188));
    hv_ds4_u16(out+23,8192); // stationary virtual accelerometer: +1g Z
    out[30]=0x1b; // USB-connected, charged virtual battery
    out[33]=1;out[34]=(uint8_t)sequence;out[35]=out[39]=0x80; // no touchpad contacts
}
/* Return a complete feature report, or -1 for unsupported IDs. No physical
   Bluetooth pairing/address is exposed by this entirely virtual USB device. */
static inline int hv_ds4_feature(unsigned report,uint8_t *out,size_t capacity) {
    unsigned n=report==2?37:report==3?48:report==0x12?16:report==0x81?7:report==0xa3?49:0;
    if(!n || capacity<n)return -1;
    memset(out,0,n);out[0]=(uint8_t)report;
    if(report==2) {
        for(unsigned i=0;i<3;i++){hv_ds4_u16(out+7+4*i,9000);hv_ds4_u16(out+9+4*i,-9000);}
        hv_ds4_u16(out+19,540);hv_ds4_u16(out+21,540);
        for(unsigned i=0;i<3;i++){hv_ds4_u16(out+23+4*i,8192);hv_ds4_u16(out+25+4*i,-8192);}
    } else if(report==0x12 || report==0x81) {
        const uint8_t address[6]={0x45,0x47,0x4e,0x45,0x48,0x02};memcpy(out+1,address,6);
    } else if(report==0xa3) {
        memcpy(out+1,"Nov 12 2026",11);memcpy(out+17,"00:00:00",8);
        hv_ds4_u16(out+35,0x0100);hv_ds4_u16(out+41,0x0100);
    } else if(report==3) {out[1]=0x21;out[2]=0x27;}
    return (int)n;
}
