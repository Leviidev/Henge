#!/usr/bin/env python3
"""Bounded ordinary-module export regression with independent FFmpeg decoding.

Inputs are generated by generate_fixtures.py. This does not launch GUI, install
plugins, test physical speakers, or qualify arbitrary formats/durations.
"""
import argparse
import array
from fractions import Fraction
import hashlib
import json
import math
import os
from pathlib import Path
import re
import subprocess


def sha(path):return hashlib.sha256(path.read_bytes()).hexdigest()
def invoke(command,**kw):return subprocess.run(command,capture_output=True,check=True,**kw)
def main():
 p=argparse.ArgumentParser(description=__doc__);p.add_argument('--candidate',type=Path,required=True);p.add_argument('--fixtures',type=Path,required=True);p.add_argument('--output',type=Path,required=True);p.add_argument('--ffmpeg',default='ffmpeg');p.add_argument('--ffprobe',default='ffprobe');a=p.parse_args();candidate=a.candidate.resolve();fixtures=a.fixtures.resolve();out=a.output.resolve();out.mkdir(parents=True,exist_ok=False)
 manifest=json.loads((fixtures/'manifest.json').read_text());assert manifest['authored']
 for name,digest in manifest['inputs'].items():assert sha(fixtures/name)==digest
 installed=json.loads((candidate/'manifest.json').read_text());app=candidate/'VLC Export Test.app'
 for name,digest in installed['signed_plugins'].items():assert sha(app/'Contents/MacOS/plugins'/name)==digest
 env=os.environ.copy()
 for key in ['DYLD_INSERT_LIBRARIES','VLC_PLUGIN_PATH','VLC_AUDIO_FIX','VLC_AUDIO_TRACE_DIR']:env.pop(key,None)
 def probe(path):return json.loads(invoke([a.ffprobe,'-v','error','-show_streams','-show_frames','-show_packets','-of','json',str(path)]).stdout)
 def pcm(path,rate=None):return invoke([a.ffmpeg,'-v','error','-i',str(path),'-vn']+(['-ar',str(rate)]if rate else[])+['-f','f32le','-']).stdout
 cases=[('x264','h264-bt601.mp4','h264'),('x265','h264-bt601.mp4','hevc'),('x265-bt709','h264-bt709.mp4','hevc'),('x264-full-sar','h264-bt709-full-sar.mp4','h264'),('x265-full-sar','h264-bt709-full-sar.mp4','hevc'),('stereo','stereo-2.003s.m4a',None)];report={}
 for name,input_name,fourcc in cases:
  d=out/name;d.mkdir();source=fixtures/input_name;output=d/'export.mp4';channels=2 if name=='stereo'else 1
  spec=(f'vcodec={fourcc},vb=2000,'if fourcc else'')+f'acodec=mp4a,ab={192 if channels==2 else 128},channels={channels},samplerate=44100'
  quoted=str(output).replace('\\','\\\\').replace('"','\\"')
  command=[str(app/'Contents/MacOS/VLC'),'-I','dummy','--config',str(candidate/'vlc-export.ini'),'--no-media-library','--verbose=2','--sout',f'#transcode{{{spec}}}:standard{{access=file,mux=mp4,dst="{quoted}"}}',str(source),'vlc://quit']
  (d/'command.json').write_text(json.dumps(command,indent=2))
  with(d/'vlc.log').open('w')as log:subprocess.run(command,env=env,stdout=log,stderr=log,timeout=180,check=True)
  original=probe(source);v=probe(output);(d/'probe.json').write_text(json.dumps(v,indent=2));streams=[]
  sa=next(s for s in original['streams']if s['codec_type']=='audio');expected=Fraction(int(sa['duration_ts']))*Fraction(sa['time_base'])*44100;expected=int(expected+Fraction(1,2))
  for s in v['streams']:
   packets=[x for x in v['packets_and_frames']if x['type']=='packet'and x['stream_index']==s['index']];frames=[x for x in v['packets_and_frames']if x['type']=='frame'and x['stream_index']==s['index']]
   ds=[x['dts']for x in packets];pts=[x['pts']for x in frames];assert all(x<y for x,y in zip(ds,ds[1:]))and all(x<y for x,y in zip(pts,pts[1:]))
   row={'codec':s['codec_name'],'frames':len(frames),'duration':s['duration'],'start':s['start_time'],'strict_dts_and_decoded_pts':True}
   if s['codec_type']=='audio':
    row['samples']=sum(x['nb_samples']for x in frames);assert row['samples']==expected;assert s['sample_rate']=='44100'and s['channels']==channels
   else:
    assert len(frames)==(60 if'full'in name else 300)
    fields=['width','height','sample_aspect_ratio','color_range','color_primaries','color_transfer','color_space'];row['metadata']={key:s.get(key)for key in fields}
    assert s['width']==1280 and s['height']==720 and s['sample_aspect_ratio']==('5:4'if'full'in name else'1:1')
    assert s['color_range']==('pc'if'full'in name else'tv')and s['color_transfer']=='bt709'
    assert s['color_primaries']==('smpte170m'if input_name=='h264-bt601.mp4'else'bt709')and s['color_space']==('bt470bg'if input_name=='h264-bt601.mp4'else'bt709')
   streams.append(row)
  warnings=invoke([a.ffmpeg,'-v','warning','-i',str(output),'-f','null','-']).stderr.decode();(d/'decode.log').write_text(warnings);assert not warnings
  audio=pcm(output);ref=array.array('f',pcm(source,44100));actual=array.array('f',audio);assert len(actual)==expected*channels and abs(len(ref)-len(actual))<=channels
  energy=sum(float(x)*x for x in ref[:len(actual)]);error=sum((float(x)-y)**2 for x,y in zip(ref,actual));snr=10*math.log10(energy/error)if error else math.inf;assert snr>20
  log=(d/'vlc.log').read_text();modules=['avgap','aacdecgap','aacpacketgap','aacgap','samplerate','stream_out_transcode','mux_mp4']+([name.split('-')[0]]if fourcc else[])
  assert all(re.search(r'using .*module "'+m+'"',log)for m in modules)
  result={'file_sha256':sha(output),'source_sha256':sha(source),'pcm_sha256':hashlib.sha256(audio).hexdigest(),'streams':streams,'expected_audio_samples':expected,'audio_snr_db':snr,'reference_extra_samples':(len(ref)-len(actual))//channels,'decode_warnings':warnings,'default_modules':modules}
  if fourcc:
   for metric,prefix,pattern in [('ssim','',r'All:([\d.]+)'),('psnr','format=gbrp,',r'average:([\d.]+)')]:
    q=invoke([a.ffmpeg,'-v','info','-i',str(source),'-i',str(output),'-filter_complex',f'[0:v]{prefix}setpts=N/(30*TB)[ref];[1:v]{prefix}setpts=N/(30*TB)[test];[ref][test]{metric}','-an','-f','null','-']).stderr.decode();(d/(metric+'.log')).write_text(q);result[metric]=float(re.findall(pattern,q)[-1])
   assert result['ssim']>.95 and result['psnr']>28
   video=next(s for s in streams if s['codec']!='aac');audio_stream=next(s for s in streams if s['codec']=='aac');result['av_start_difference_us']=(float(video['start'])-float(audio_stream['start']))*1e6;assert abs(result['av_start_difference_us'])<25
  report[name]=result;(out/'validation.json').write_text(json.dumps(report,indent=2));print(name,'PASS',flush=True)
 assert report['x264']['pcm_sha256']==report['x265']['pcm_sha256']==report['x265-bt709']['pcm_sha256'];assert report['x264-full-sar']['pcm_sha256']==report['x265-full-sar']['pcm_sha256']
 (out/'status.json').write_text(json.dumps({'status':'passed','cases':len(report),'candidate_manifest_sha256':sha(candidate/'manifest.json'),'fixture_manifest_sha256':sha(fixtures/'manifest.json'),'limits':'Native default-chain regression only; guest/GUI/physical speaker are separate gates.'},indent=2))
if __name__=='__main__':main()
